#!/usr/bin/env python3
"""Assemble our readable surrogates; generate the private build's C++ header.
Requires clang (cross-target ELF supported even on the macOS build host).
GNU cc fallback is for x86-64 Linux host tests only. No downloaded payloads.
"""
from pathlib import Path
import shutil,struct,subprocess,tempfile,sys
here=Path(__file__).resolve().parent

def generate(destination):
    clang=shutil.which('clang')
    command=[clang,'--target=x86_64-unknown-linux-gnu'] if clang else ['cc']
    with tempfile.TemporaryDirectory() as d:
        obj=Path(d)/'leaf.o'
        subprocess.run(command+['-c',str(here/'QueenGuestLeafSurrogates.S'),'-o',str(obj)],check=True)
        b=obj.read_bytes()
    assert b[:6]==b'\x7fELF\x02\x01' and struct.unpack_from('<H',b,18)[0]==62, 'expected little-endian x86-64 ELF'
    off=struct.unpack_from('<Q',b,40)[0]
    entsize,count,names=struct.unpack_from('<HHH',b,58)
    sections=[struct.unpack_from('<IIQQQQIIQQ',b,off+i*entsize) for i in range(count)]
    sh=sections[names]; strings=b[sh[4]:sh[4]+sh[5]]
    content={}
    for sh in sections:
        name=strings[sh[0]:].split(b'\0',1)[0].decode()
        assert not (sh[1] in (4,9) and sh[5]), 'relocations forbidden in surrogate object'
        if name in ('.text.queen_tls','.text.queen_tid'):
            content[name]=b[sh[4]:sh[4]+sh[5]]
    out='#pragma once\n#include <cstdint>\n// Generated from QueenGuestLeafSurrogates.S; do not publish generated bytes.\nnamespace queen_guest_leaf {\n'
    for section,name in [('.text.queen_tls','TlsGetValue'),('.text.queen_tid','GetCurrentThreadId')]:
        code=content[section]; assert 0<len(code)<=128
        out+='inline constexpr uint8_t '+name+'[] = {'+','.join(hex(v) for v in code)+'};\n'
    Path(destination).write_text(out+'}\n')
if __name__=='__main__':
    generate(sys.argv[1])
