import UIKit

@MainActor func checkControllerFallback() {
    precondition(Set(BCDControllerFallbackActions.names).count == 16)
    precondition(BCDControllerFallbackActions.sample("A")?.buttons == 0x1000)
    precondition(BCDControllerFallbackActions.sample("B")?.buttons == 0x2000)
    precondition(BCDControllerFallbackActions.sample("View")?.buttons == 0x20)
    precondition(BCDControllerFallbackActions.sample("Menu")?.buttons == 0x10)
    precondition(BCDControllerFallbackActions.sample("LT")?.lt == 255)
    precondition(BCDControllerFallbackActions.sample("RT")?.rt == 255)
    precondition(BCDControllerFallbackActions.sample("Confirm") == nil)
    let view = BCDControllerFallbackView()
    var held: [UUID: GamepadSample] = [:]
    let sink: (UUID, GamepadSample?) -> Void = { owner, value in held[owner] = value }
    let epoch = UUID(), a = UUID(), b = UUID()
    view.configure(accepting:true,reset:epoch,output:sink)
    view.begin(owner:a,action:"A"); view.begin(owner:b,action:"RT")
    precondition(held.count == 2 && held[a]?.buttons == 0x1000 && held[b]?.rt == 255)
    view.end(owner:a)
    precondition(held.count == 1 && held[b]?.rt == 255)
    view.configure(accepting:false,reset:epoch,output:sink)
    precondition(held.isEmpty)
    view.begin(owner:a,action:"B"); precondition(held.isEmpty)
    view.configure(accepting:true,reset:epoch,output:sink)
    view.begin(owner:a,action:"LB")
    view.configure(accepting:true,reset:UUID(),output:sink)
    precondition(held.isEmpty)
    view.begin(owner:a,action:"A")
    NotificationCenter.default.post(name:UIApplication.willResignActiveNotification,object:nil)
    precondition(held.isEmpty)
    view.begin(owner:a,action:"X"); NotificationCenter.default.post(name:BCDPackFocus.didLoseFocus,object:nil)
    precondition(held.isEmpty)
    view.begin(owner:a,action:"X"); view.cancelAll(); view.cancelAll()
    precondition(held.isEmpty)
    view.begin(owner:b,action:"Y")
    view.frame = CGRect(x:0,y:0,width:400,height:220); view.layoutSubviews()
    precondition(held.isEmpty)
    view.begin(owner:a,action:"Menu"); view.didMoveToWindow()
    precondition(held.isEmpty)
}
